#ifndef SPIRIT_LIFECYCLE_H
#define SPIRIT_LIFECYCLE_H

// ════════════════════════════════════════════════════════════════════════
// 精灵生命周期：存活 → 死亡 → 消逝
//
// 三者是**不同机制**，不是同一条路径上的强弱档（用户 2026-09-17 拍板）：
//   - 存活：hp > 0
//   - 死亡：hp <= 0（体力归零）。可被复活（真2命 / 重生），**仍占位**、
//     仍属于背包/场下（故"相邻/隔位"判定照旧算它）。
//   - 消逝：**体力上限归零**（官方「体力上限直接变成 0/0」，idx=402 + 初稿 idx=209）。
//     消逝蕴含阵亡，但比死亡更强：从**所有空间定义**里剔除（官方 idx=149：
//     消逝不属于"背包/场上/场下/不在场"）、从**位置基准**里挖空（官方 idx=56：
//     "当二边精灵被消逝时会跨1位，直接跳过该精灵位置"）、不可被复活
//     （"被消逝的精灵除外"，idx=251）。
//
// ★ 表示法：**消逝 = numericalBase[HP] == 0**，不新增布尔位。一条不变量贯穿全引擎：
//     is_vanished ⇔ hp<=0 && 上限<=0
//   "上限为 0" 只能由消逝产生——数值削减类效果（空元卪、阿尔忒弥斯…）一律经
//   reduce_max_hp_* 原语，**下限钳在 1**（用户口径），永远不会削到 0。
//   于是"上限==0"与"被消逝"严格等价，查询处不必再判第二个条件。
//   （收敛在 BattleContext::is_vanished 一处：将来若要改表示法只改那一个函数。）
//
// 死亡漏斗的两个拦截层**必须分开**，因为官方对"消耗全部体力"的可见性不同
// （idx=339《赛学选修4—免死》）：
//   - 残留体力免死：「所有的残留体力效果面对消耗体力效果，都不能免死，会被直接强制死亡」
//   - 复活（真2命/重生）：「复活效果面对消耗体力效果……另外二类复活只要触发就可以当回合不死」
//   → DeathInterceptor::sees_hp_consume 表达这一区分，别合成一个"保命"钩子。
// ════════════════════════════════════════════════════════════════════════

#include <functional>

class BattleContext;

// 本次倒下的成因。拦截器按成因决定可见性（见上：消耗体力穿残留免死、不穿复活）。
enum class DefeatCause {
    DAMAGE = 0,       // 伤害致死（红伤/粉伤/真伤）
    INSTANT_KILL = 1, // 秒杀族（force_hp_to_zero）——受"免疫秒杀"票影响，可被短路转化
    HP_CONSUME = 2,   // 消耗全部体力（自爆族/咤150/白龙玄祖）——**不响应**免疫秒杀、穿所有残留免死
    EFFECT = 3,       // 效果直接扣血/直写归零（含对场下精灵的结算）
};

// defeat_pet 的结果。
enum class DefeatResult {
    DEFEATED = 0,     // 本次死亡成立（已标记 + emit EVENT_DEATH）
    INTERCEPTED = 1,  // 被拦截器拦下（免死/复活），目标未死
    ALREADY_DEAD = 2, // 该槽的本次死亡已登记过（幂等重入）
    NOT_DOWN = 3,     // 体力仍 > 0，不构成死亡
    INVALID = 4,      // 参数非法
};

// 「阵亡计数」的空间口径（官方 idx=149 §4.1.1 的四个术语，措辞即判据）：
//   ROSTER        「背包」   = 己方 6 个出战精灵（消逝除外）——含在场那只
//   OFF_FIELD     「场下」   = 除在场精灵外的其他 5 个（消逝除外）
//   NOT_ON_STAGE  「不在场」 = 场下 + **额外精灵**
//   ALL           「全部阵亡」= 背包 + **额外精灵**
// 判别轴是官方措辞：写明"背包"用 ROSTER（飞王"背包内每有1只阵亡则先制+1"、
// 哈肯撒余恨）；写明"己方场下"用 OFF_FIELD；**没写限定词的默认含额外精灵**
// 用 ALL（帝君"己方每有一只阵亡则增伤减伤"、西叶"双方每死亡1只"）。
// 已消逝的精灵**四个口径都不计**（官方 idx=172："涉及到队友存活或者死亡收益的，默认会被消逝"）。
enum class DeadScope {
    ROSTER = 0,
    OFF_FIELD = 1,
    NOT_ON_STAGE = 2,
    ALL = 3,
};

// 额外精灵的三态（官方 idx=149 #总结：额外精灵"没有血量、没有pp、没有技能，
// 只有存活、死亡、消逝三个状态，同时不在己方背包、不在场上、不在己方场下"）。
enum class ExtraSpiritState {
    ALIVE = 0,
    DEAD = 1,
    VANISHED = 2,
};

// 额外精灵条目：**独立容器**，绝不进 6 槽数组（那会污染全引擎每一处 for(slot<6)）。
// 官方例：乔特鲁德的黑白龙（金祖/玄祖）、魂帝咽咎尸骸（"每有1层视为己方拥有1只
// 阵亡的邪灵系额外精灵"）。
struct ExtraSpirit {
    int element = 0;               // 系别 id（邪灵/金/玄…），供"剥离单系别"类效果查询
    ExtraSpiritState state = ExtraSpiritState::ALIVE;
    int source_effect_id = 0;      // 来源效果（咽咎尸骸 / 黑白龙…）
    int source_side = -1;          // 归属方
    int linked_slot = -1;          // 关联本体槽（-1 = 无本体，如魂帝尸骸）
    // 本体死亡或被消逝**不影响**额外精灵（官方 idx=149 #6）——故本容器与 pet 解耦。
};

// 死亡拦截器：返回 true = 本次死亡被拦下。
// 契约：拦下时必须把目标的 hp 写回 > 0（免死写残留值、复活写记录体力）；
//       defeat_pet 会复核 hp>0，只声明不落地的拦截器视为未拦下（防"幽灵拦截"）。
struct DeathInterceptor {
    int source_effect_id = 0;    // 来源效果 id（去重/注销用）
    int owner = -1;              // 注册方（-1 = 任意方）
    bool sees_hp_consume = false; // 是否对 DefeatCause::HP_CONSUME 可见
                                  //   false = 残留体力免死（官方：不能被消耗体力免死）
                                  //   true  = 复活/真2命（官方：触发就可不死）
    std::function<bool(BattleContext*, int side, int slot, int actor, DefeatCause cause)> fn;
};

#endif // SPIRIT_LIFECYCLE_H
